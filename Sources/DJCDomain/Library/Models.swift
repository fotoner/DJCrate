import Foundation

public struct Track: Sendable, Identifiable, Hashable {
    public let id: String
    public let uuid: String
    public let title: String
    public let artist: String?
    public let album: String?
    public let albumArtist: String?
    public let genre: String?
    public let composer: String?
    public let releaseYear: Int?
    public let trackNumber: Int?
    public let key: String?
    /// rekordbox는 BPM을 100배 정수로 저장한다. 미분석이면 nil.
    public let bpm: Double?
    public let lengthSeconds: Int
    /// DB의 kbps. 미분석·알 수 없는 값은 nil.
    public let bitrateKbps: Int?
    public let folderPath: String
    /// DB에 저장된 코멘트 원문(정규화 전).
    public let comment: String
    /// `created_at` 앞 10자리(YYYY-MM-DD). 컬렉션 임포트 시점으로 쓴다.
    public let importedOn: String?
    public let analysisDataPath: String?
    /// `/PIONEER/Artwork/…/artwork.jpg` (rekordbox share 기준)
    public let imagePath: String?
    /// 컬렉션에서 삭제됐지만 행이 남아 있는 tombstone.
    public let isDeleted: Bool
    /// 평점(`Rating`, 별 수 0~5). 0이면 없음.
    public let rating: Int
    /// 곡 색(`ColorID` = `djmdColor.ID`). 없으면('0'·''·NULL) nil.
    public let colorID: String?
    /// 곡 행의 클라우드 동기화 상태(`rb_data_status`, 0·256·257 …). 추가한 곡(아직 rekordbox에 없음)은 nil.
    public let dataStatus: Int?

    public init(id: String, uuid: String, title: String, artist: String?, album: String?, albumArtist: String?,
                genre: String?, composer: String?, releaseYear: Int?, trackNumber: Int?, key: String?, bpm: Double?,
                lengthSeconds: Int, folderPath: String, comment: String, importedOn: String?,
                analysisDataPath: String?, imagePath: String?, isDeleted: Bool, bitrateKbps: Int? = nil,
                rating: Int = 0, colorID: String? = nil, dataStatus: Int? = nil) {
        self.id = id; self.uuid = uuid; self.title = title; self.artist = artist; self.album = album
        self.albumArtist = albumArtist; self.genre = genre; self.composer = composer; self.releaseYear = releaseYear
        self.trackNumber = trackNumber; self.key = key; self.bpm = bpm; self.lengthSeconds = lengthSeconds
        self.folderPath = folderPath; self.comment = comment; self.importedOn = importedOn
        self.analysisDataPath = analysisDataPath; self.imagePath = imagePath; self.isDeleted = isDeleted
        self.bitrateKbps = bitrateKbps.flatMap { $0 > 0 ? $0 : nil }
        self.rating = rating
        // rekordbox는 색을 지우면 '0'을 쓴다(2026-10-04 묶음 2 S3). ''·NULL도 없음으로 읽는다.
        self.colorID = colorID.flatMap { $0.isEmpty || $0 == "0" ? nil : $0 }
        self.dataStatus = dataStatus
    }

    /// 스트리밍 트랙(`apple-music:…`, `spotify:…` 등)은 로컬 파일 경로가 없다.
    public var isStreaming: Bool { !folderPath.hasPrefix("/") }

    public var importYear: String? { importedOn.map { String($0.prefix(4)) } }

    public var fileExtension: String {
        isStreaming ? "stream" : (folderPath as NSString).pathExtension.lowercased()
    }
}

public struct Cue: Sendable, Hashable {
    /// `djmdCue.ID`
    public let id: String
    public let contentID: String
    /// 0 = 메모리 큐, 그 외 = 핫큐 슬롯. `hotCueSlot` 참고.
    public let kind: Int
    public let inMsec: Int
    public let name: String
    public let colorTableIndex: Int?
    /// 루프 끝(ms). 루프가 아니면 0 이하.
    public var outMsec: Int = 0
    /// rekordbox 색 값(255 = 색 없음)
    public var color: Int?
    /// 자동 루프(ActiveLoop) 표시
    public var activeLoop: Int = 0
    /// 박 루프 크기(상위 16비트 = 박 수, 하위 = 1). 박으로 잡은 루프가 아니면 0.
    public var beatLoopSize: Int = 0

    public init(id: String, contentID: String, kind: Int, inMsec: Int, name: String, colorTableIndex: Int?,
                outMsec: Int = 0, color: Int? = nil, activeLoop: Int = 0, beatLoopSize: Int = 0) {
        self.id = id; self.contentID = contentID; self.kind = kind; self.inMsec = inMsec; self.name = name
        self.colorTableIndex = colorTableIndex; self.outMsec = outMsec; self.color = color; self.activeLoop = activeLoop
        self.beatLoopSize = beatLoopSize
    }

    public var isMemoryCue: Bool { kind == 0 }
    public var isLoop: Bool { outMsec > inMsec }

    /// rekordbox가 자동으로 붙이는 이름. 이 이름의 큐는 사용자가 직접 찍은 큐로 보지 않는다.
    public static let autoNames: Set<String> = ["CUE(Auto)", "1.1Bars"]
    public var isAutoGenerated: Bool { Cue.autoNames.contains(name.trimmingCharacters(in: .whitespaces)) }

    /// 실측 분포 기반 매핑(1,2,3 → A,B,C / 5…9 → D…H). Kind 4의 의미는 미확인.
    public var hotCueSlot: Character? {
        switch kind {
        case 1: "A"
        case 2: "B"
        case 3: "C"
        case 5: "D"
        case 6: "E"
        case 7: "F"
        case 8: "G"
        case 9: "H"
        default: nil
        }
    }
}
