import Foundation

/// 라이브러리 현황 집계(값). 실제 컬렉션(삭제 행 제외)만 센다.
public struct LibraryReport: Sendable {
    public var totalRows = 0
    public var deletedRows = 0
    public var liveTracks = 0
    public var streamingTracks = 0
    public var extensions: [String: Int] = [:]
    public var commentClasses: [String: Int] = [:]
    public var prefixes: [String: Int] = [:]
    public private(set) var hasCommentRule = false
    public private(set) var matchingComments = 0
    public var usages: [String: Int] = [:]
    public var emptyByImportYear: [String: Int] = [:]
    public var tracksWithCues = 0
    public var tracksWithManualCues = 0
    public var tracksWithOnlyAutoCues = 0
    public var tracksWithoutCues = 0
    public var hotCueSlots: [Character: Int] = [:]
    public var playedTracks = 0
    public var emptyCommentPlayed = 0
    public var missingFiles: Int?

    /// - Parameter fileExists: 주면 스트리밍이 아닌 곡의 음원 파일이 있는지 세어 `missingFiles`에 적는다(파일 확인은 부르는 쪽이 준다)
    public init(library: RekordboxLibrary, fileExists: ((String) -> Bool)? = nil, commentRule: (any CommentRule)? = nil) {
        totalRows = library.allTracks.count
        let live = library.tracks
        liveTracks = live.count
        deletedRows = totalRows - liveTracks

        applyCommentRule(commentRule, comments: live.map(\.comment))
        var missing = 0
        for track in live {
            extensions[track.fileExtension, default: 0] += 1
            if track.isStreaming {
                streamingTracks += 1
            } else if let fileExists, !fileExists(track.folderPath) {
                missing += 1
            }

            let empty = CommentText.normalize(track.comment).isEmpty
            if empty { emptyByImportYear[track.importYear ?? "?", default: 0] += 1 }

            let cues = library.cues(for: track)
            if cues.isEmpty {
                tracksWithoutCues += 1
            } else {
                tracksWithCues += 1
                if cues.contains(where: { !$0.isAutoGenerated }) {
                    tracksWithManualCues += 1
                } else {
                    tracksWithOnlyAutoCues += 1
                }
            }
            for cue in cues where !cue.isAutoGenerated {
                if let slot = cue.hotCueSlot { hotCueSlots[slot, default: 0] += 1 }
            }

            if library.playCounts[track.id, default: 0] > 0 {
                playedTracks += 1
                if empty { emptyCommentPlayed += 1 }
            }
        }
        if fileExists != nil { missingFiles = missing }
    }

    /// 프리셋 전환은 이미 읽은 코멘트만 다시 집계한다.
    public mutating func applyCommentRule(_ rule: (any CommentRule)?, comments: [String]) {
        hasCommentRule = rule != nil
        commentClasses = [:]; prefixes = [:]; usages = [:]; matchingComments = 0
        guard let rule else { return }
        for comment in comments {
            let result = rule.evaluate(comment)
            commentClasses[result.classification, default: 0] += 1
            if result.isMatch { matchingComments += 1 }
            if let prefix = result.prefix { prefixes[prefix, default: 0] += 1 }
            for usage in result.usages { usages[usage, default: 0] += 1 }
        }
    }

    public func render() -> String {
        func sorted<K>(_ dict: [K: Int], key: (K) -> String) -> String {
            dict.sorted { $0.value > $1.value }.map { "\(key($0.key)) \($0.value)" }.joined(separator: " · ")
        }
        var lines: [String] = []
        lines.append(String(ui: "## 컬렉션"))
        lines.append(String(ui: "전체 행 \(totalRows) = 실제 컬렉션 \(liveTracks) + 삭제 행 \(deletedRows)"))
        lines.append(String(ui: "포맷: ") + sorted(extensions) { $0 })
        if let missingFiles { lines.append(String(ui: "접근 불가 파일: \(missingFiles) (스트리밍 \(streamingTracks) 제외)")) }
        lines.append("")
        lines.append(String(ui: "## 코멘트"))
        if hasCommentRule {
            lines.append(String(ui: "분류: ") + sorted(commentClasses) { $0 })
            lines.append(String(ui: "접두어: ") + sorted(prefixes) { $0 })
            lines.append(String(ui: "용도: ") + sorted(usages) { $0 })
        }
        lines.append(String(ui: "빈 코멘트 임포트 연도: ") + emptyByImportYear.sorted { $0.key < $1.key }.map { "\($0.key) \($0.value)" }.joined(separator: " · "))
        lines.append("")
        lines.append(String(ui: "## 큐"))
        lines.append(String(ui: "큐 있음 \(tracksWithCues) (수동 \(tracksWithManualCues) · 자동만 \(tracksWithOnlyAutoCues)) · 큐 없음 \(tracksWithoutCues)"))
        lines.append(String(ui: "수동 핫큐 슬롯: ") + hotCueSlots.sorted { $0.key < $1.key }.map { "\($0.key) \($0.value)" }.joined(separator: " · "))
        lines.append("")
        lines.append(String(ui: "## 재생"))
        lines.append(String(ui: "재생 기록 있는 곡 \(playedTracks) · 그중 빈 코멘트 \(emptyCommentPlayed)"))
        return lines.joined(separator: "\n")
    }
}
