import Foundation

/// 라이브러리 읽기 결과의 값(CLI 읽기 명령의 JSON 계약 `LibraryRead`과 앱의 중복 후보 화면이 함께 쓴다).
public enum LibraryRecords {
    public struct TrackRecord: Codable, Sendable {
        public let id: String
        public let uuid: String
        public let title: String
        public let artist: String?
        public let album: String?
        public let albumArtist: String?
        public let genre: String?
        public let composer: String?
        public let releaseYear: Int?
        public let trackNumber: Int?
        public let key: String?
        public let bpm: Double?
        public let lengthSeconds: Int
        public let path: String
        public let comment: String
        public let importedOn: String?
        public let isStreaming: Bool

        public init(_ track: Track) {
            id = track.id; uuid = track.uuid; title = track.title; artist = track.artist
            album = track.album; albumArtist = track.albumArtist; genre = track.genre; composer = track.composer
            releaseYear = track.releaseYear; trackNumber = track.trackNumber; key = track.key; bpm = track.bpm
            lengthSeconds = track.lengthSeconds; path = track.folderPath; comment = track.comment
            importedOn = track.importedOn; isStreaming = track.isStreaming
        }
    }

    public struct DuplicateMember: Codable, Sendable, Identifiable {
        public let track: TrackRecord
        public let cueCount: Int
        public let manualCueCount: Int
        public let playlistCount: Int
        public let playCount: Int
        public let format: String
        public let bitrateKbps: Int?
        /// rekordbox `ImagePath`(`/PIONEER/Artwork/…/artwork.jpg`). 그림이 없으면 nil
        public let imagePath: String?
        public var id: String { track.id }
    }

    public struct DuplicateGroup: Codable, Sendable, Identifiable {
        public let id: String
        public let tracks: [DuplicateMember]
    }

    public struct DuplicateList: Codable, Sendable {
        public let lengthToleranceSeconds: Int
        public let groups: [DuplicateGroup]
    }

    /// 중복 후보 묶음(길이 2초 이내 같은 곡)과 묶음마다 곡의 큐·재생 목록·재생 수·음질
    public static func duplicates(in library: RekordboxLibrary) -> DuplicateList {
        let tracks = library.tracks
        let byID = Dictionary(tracks.map { ($0.id, $0) }, uniquingKeysWith: { first, _ in first })
        var playlistCounts: [String: Int] = [:]
        // 같은 재생 목록의 반복 항목은 한 번만 센다. 폴더는 직접 소속이 아니다.
        for playlist in library.playlists where !playlist.isFolder {
            for id in Set(playlist.trackIDs) { playlistCounts[id, default: 0] += 1 }
        }
        let groups = DuplicateTracks.groups(in: tracks).map { group in
            DuplicateGroup(id: group.id, tracks: group.trackIDs.compactMap { id in
                guard let track = byID[id] else { return nil }
                let cues = library.cues(for: track)
                return DuplicateMember(track: TrackRecord(track), cueCount: cues.count,
                                       manualCueCount: cues.filter { !$0.isAutoGenerated }.count,
                                       playlistCount: playlistCounts[id, default: 0],
                                       playCount: library.playCounts[id, default: 0],
                                       format: track.fileExtension.uppercased(), bitrateKbps: track.bitrateKbps,
                                       imagePath: track.imagePath?.isEmpty == false ? track.imagePath : nil)
            })
        }
        return DuplicateList(lengthToleranceSeconds: DuplicateTracks.lengthToleranceSeconds, groups: groups)
    }

    // MARK: - CLI 읽기 명령 결과(JSON 계약, DJCStorage `LibraryRead`가 만든다)

    public struct TrackList: Codable, Sendable {
        public let tracks: [TrackRecord]
        public init(tracks: [TrackRecord]) { self.tracks = tracks }
    }
    public struct PathList: Codable, Sendable {
        public let paths: [String]
        public init(paths: [String]) { self.paths = paths }
    }
    public struct CueRecord: Codable, Sendable {
        public let id: String
        public let kind: Int
        public let hotCueSlot: String?
        public let inMsec: Int
        public let outMsec: Int
        public let name: String
        public let isLoop: Bool
        public let activeLoop: Bool
        public let loopBeats: Double?
        public let isAutoGenerated: Bool
        public let color: Int?
        public let colorTableIndex: Int?

        public init(_ cue: Cue) {
            id = cue.id; kind = cue.kind; hotCueSlot = cue.hotCueSlot.map(String.init)
            inMsec = cue.inMsec; outMsec = cue.outMsec; name = cue.name; isLoop = cue.isLoop
            activeLoop = cue.activeLoop > 0; loopBeats = EditableCue.Loop.beats(beatLoopSize: cue.beatLoopSize)
            isAutoGenerated = cue.isAutoGenerated; color = cue.color; colorTableIndex = cue.colorTableIndex
        }
        public init(id: String, kind: Int, hotCueSlot: String?, inMsec: Int, outMsec: Int, name: String, isLoop: Bool, activeLoop: Bool, loopBeats: Double?, isAutoGenerated: Bool, color: Int?, colorTableIndex: Int?) {
            self.id = id; self.kind = kind; self.hotCueSlot = hotCueSlot; self.inMsec = inMsec; self.outMsec = outMsec; self.name = name; self.isLoop = isLoop; self.activeLoop = activeLoop; self.loopBeats = loopBeats; self.isAutoGenerated = isAutoGenerated; self.color = color; self.colorTableIndex = colorTableIndex
        }
    }

    public struct GridRecord: Codable, Sendable {
        public let status: String
        public let beatCount: Int
        public let segments: [GridSegment]
        public let tempoChanges: [Double]
        public init(status: String, beatCount: Int, segments: [GridSegment], tempoChanges: [Double]) {
            self.status = status; self.beatCount = beatCount; self.segments = segments; self.tempoChanges = tempoChanges
        }
    }

    public struct GainRecord: Codable, Sendable {
        public let linear: Double
        public let decibels: Double
        public let peak: Double?
        public init(linear: Double, decibels: Double, peak: Double?) {
            self.linear = linear; self.decibels = decibels; self.peak = peak
        }
    }

    public struct DraftState: Codable, Sendable {
        public let cue: Bool
        public let grid: Bool
        public let gain: Bool
        public let tag: Bool
        /// 그림 초안(#66)
        public var artwork = false
        public var kinds: [String] {
            [("cue", cue), ("grid", grid), ("gain", gain), ("tag", tag), ("artwork", artwork)].compactMap { $0.1 ? $0.0 : nil }
        }
        public init(cue: Bool, grid: Bool, gain: Bool, tag: Bool) {
            self.cue = cue; self.grid = grid; self.gain = gain; self.tag = tag
        }
    }

    public struct PlaylistRecord: Codable, Sendable {
        public let id: String
        public let name: String
        public let parentID: String
        public let sequence: Int
        public let isFolder: Bool
        public let trackCount: Int
        public let children: [PlaylistRecord]?
        public init(id: String, name: String, parentID: String, sequence: Int, isFolder: Bool, trackCount: Int, children: [PlaylistRecord]?) {
            self.id = id; self.name = name; self.parentID = parentID; self.sequence = sequence; self.isFolder = isFolder; self.trackCount = trackCount; self.children = children
        }
    }

    public struct PlaylistList: Codable, Sendable {
        public let playlists: [PlaylistRecord]
        public init(playlists: [PlaylistRecord]) { self.playlists = playlists }
    }
    public struct PlaylistContents: Codable, Sendable {
        public let playlist: PlaylistRecord
        public let tracks: [TrackRecord]
        public init(playlist: PlaylistRecord, tracks: [TrackRecord]) {
            self.playlist = playlist; self.tracks = tracks
        }
    }

    public struct HistoryRecord: Codable, Sendable {
        public let id: String
        public let name: String
        public let dateCreated: String?
        public let trackCount: Int
        public init(id: String, name: String, dateCreated: String?, trackCount: Int) {
            self.id = id; self.name = name; self.dateCreated = dateCreated; self.trackCount = trackCount
        }
    }

    public struct HistoryEntry: Codable, Sendable {
        public let id: String
        public let trackNumber: Int
        public let track: TrackRecord
        public init(id: String, trackNumber: Int, track: TrackRecord) {
            self.id = id; self.trackNumber = trackNumber; self.track = track
        }
    }

    public struct HistoryList: Codable, Sendable {
        public let histories: [HistoryRecord]
        public init(histories: [HistoryRecord]) { self.histories = histories }
    }
    public struct HistoryContents: Codable, Sendable {
        public let history: HistoryRecord
        public let entries: [HistoryEntry]
        public init(history: HistoryRecord, entries: [HistoryEntry]) {
            self.history = history; self.entries = entries
        }
    }

    public struct TrackInfo: Codable, Sendable {
        public let track: TrackRecord
        public let cues: [CueRecord]
        public let grid: GridRecord
        public let gain: GainRecord?
        public let playlists: [PlaylistRecord]
        public let drafts: DraftState
        public init(track: TrackRecord, cues: [CueRecord], grid: GridRecord, gain: GainRecord?, playlists: [PlaylistRecord], drafts: DraftState) {
            self.track = track; self.cues = cues; self.grid = grid; self.gain = gain; self.playlists = playlists; self.drafts = drafts
        }
    }

    public struct DraftRecord: Codable, Sendable {
        public let trackUUID: String
        public let contentID: String?
        public let title: String?
        public let kinds: [String]
        public init(trackUUID: String, contentID: String?, title: String?, kinds: [String]) {
            self.trackUUID = trackUUID; self.contentID = contentID; self.title = title; self.kinds = kinds
        }
    }

    public struct DraftList: Codable, Sendable {
        public let drafts: [DraftRecord]
        public init(drafts: [DraftRecord]) { self.drafts = drafts }
    }
    public struct Report: Codable, Sendable {
        public let totalRows: Int
        public let deletedRows: Int
        public let liveTracks: Int
        public let streamingTracks: Int
        public let extensions: [String: Int]
        public let commentClasses: [String: Int]?
        public let prefixes: [String: Int]?
        public let usages: [String: Int]?
        public let emptyByImportYear: [String: Int]
        public let tracksWithCues: Int
        public let tracksWithManualCues: Int
        public let tracksWithOnlyAutoCues: Int
        public let tracksWithoutCues: Int
        public let hotCueSlots: [String: Int]
        public let playedTracks: Int
        public let emptyCommentPlayed: Int
        public let missingFiles: Int?
        public init(totalRows: Int, deletedRows: Int, liveTracks: Int, streamingTracks: Int, extensions: [String: Int], commentClasses: [String: Int]?, prefixes: [String: Int]?, usages: [String: Int]?, emptyByImportYear: [String: Int], tracksWithCues: Int, tracksWithManualCues: Int, tracksWithOnlyAutoCues: Int, tracksWithoutCues: Int, hotCueSlots: [String: Int], playedTracks: Int, emptyCommentPlayed: Int, missingFiles: Int?) {
            self.totalRows = totalRows; self.deletedRows = deletedRows; self.liveTracks = liveTracks; self.streamingTracks = streamingTracks; self.extensions = extensions; self.commentClasses = commentClasses; self.prefixes = prefixes; self.usages = usages; self.emptyByImportYear = emptyByImportYear; self.tracksWithCues = tracksWithCues; self.tracksWithManualCues = tracksWithManualCues; self.tracksWithOnlyAutoCues = tracksWithOnlyAutoCues; self.tracksWithoutCues = tracksWithoutCues; self.hotCueSlots = hotCueSlots; self.playedTracks = playedTracks; self.emptyCommentPlayed = emptyCommentPlayed; self.missingFiles = missingFiles
        }

        /// 라이브러리 현황(`LibraryReport`)의 JSON 계약 값. 코멘트 규칙이 없으면 코멘트 칸은 비운다
        public init(_ report: LibraryReport) {
            self.init(totalRows: report.totalRows, deletedRows: report.deletedRows, liveTracks: report.liveTracks,
                      streamingTracks: report.streamingTracks, extensions: report.extensions,
                      commentClasses: report.hasCommentRule ? report.commentClasses : nil,
                      prefixes: report.hasCommentRule ? report.prefixes : nil,
                      usages: report.hasCommentRule ? report.usages : nil, emptyByImportYear: report.emptyByImportYear,
                      tracksWithCues: report.tracksWithCues, tracksWithManualCues: report.tracksWithManualCues,
                      tracksWithOnlyAutoCues: report.tracksWithOnlyAutoCues, tracksWithoutCues: report.tracksWithoutCues,
                      hotCueSlots: Dictionary(uniqueKeysWithValues: report.hotCueSlots.map { (String($0.key), $0.value) }),
                      playedTracks: report.playedTracks, emptyCommentPlayed: report.emptyCommentPlayed, missingFiles: report.missingFiles)
        }
    }

    public struct ParsedComment: Codable, Sendable {
        public struct Parsed: Codable, Sendable {
            public struct Usage: Codable, Sendable {
                public let kind: String
                public let numbers: [Int]
                public init(kind: String, numbers: [Int]) { self.kind = kind; self.numbers = numbers }
            }
            public let prefix: String
            public let workRef: String
            public let workName: String
            public let season: Int?
            public let seasonStyle: String?
            public let abbreviations: [String]
            public let usages: [Usage]
            public let episodes: [Int]
            public let isCharacterSong: Bool
            public let isTVSize: Bool
            public let variants: [String]
            public let isFormerAffiliation: Bool
            public let airingYear: Int?
            public let airingQuarter: Int?
            public let movieYear: Int?
            public let boomboxVolumes: [Int]

            public init(prefix: String, workRef: String, workName: String, season: Int?, seasonStyle: String?, abbreviations: [String],
                        usages: [Usage], episodes: [Int], isCharacterSong: Bool, isTVSize: Bool, variants: [String], isFormerAffiliation: Bool,
                        airingYear: Int?, airingQuarter: Int?, movieYear: Int?, boomboxVolumes: [Int]) {
                self.prefix = prefix; self.workRef = workRef; self.workName = workName; self.season = season; self.seasonStyle = seasonStyle
                self.abbreviations = abbreviations; self.usages = usages; self.episodes = episodes; self.isCharacterSong = isCharacterSong
                self.isTVSize = isTVSize; self.variants = variants; self.isFormerAffiliation = isFormerAffiliation; self.airingYear = airingYear
                self.airingQuarter = airingQuarter; self.movieYear = movieYear; self.boomboxVolumes = boomboxVolumes
            }
        }
        public let classification: String
        public let parsed: Parsed?

        public init(classification: String, parsed: Parsed?) {
            self.classification = classification
            self.parsed = parsed
        }
    }

    public struct Compatibility: Codable, Sendable {
        public let appVersion: String?
        public let verifiedAppVersions: [String]
        public let databaseVersion: String
        public let localUpdateCount: Int?
        public let cloudUpdateCount: Int?
        public init(appVersion: String?, verifiedAppVersions: [String], databaseVersion: String, localUpdateCount: Int?, cloudUpdateCount: Int?) {
            self.appVersion = appVersion; self.verifiedAppVersions = verifiedAppVersions; self.databaseVersion = databaseVersion; self.localUpdateCount = localUpdateCount; self.cloudUpdateCount = cloudUpdateCount
        }
    }
}
