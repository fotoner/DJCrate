                                     .writeVerificationFailed("검증")]
        for error in errors { #expect(!error.description.isEmpty) }
        #expect(DJCError.writeRefused("이유").description.contains("이유"))
    }
}

@Suite("박 위치·변속")
struct BeatGridPositionTests {
    /// 120 BPM 16박(1.0초부터, 첫 박 번호 3) → 다운비트 2.0, 4.0, 6.0, 8.0
    let grid = BeatGrid(beats: (0..<16).map { BeatGrid.Beat(number: ($0 + 2) % 4 + 1, bpm: 120, time: 1.0 + Double($0) * 0.5) })

    @Test func 마디와_마디점박() {
        #expect(grid.downbeats == [2.0, 4.0, 6.0, 8.0])
        #expect(grid.bar(at: 1.9) == 0 && grid.bar(at: 2.0) == 1 && grid.bar(at: 5.9) == 2)
        #expect(grid.positionText(at: 0.9) == nil)
        #expect(grid.positionText(at: 1.0) == "0.3" && grid.positionText(at: 2.0) == "1.1" && grid.positionText(at: 2.6) == "1.2")
    }

    @Test func 스냅과_박_이동() {
        #expect(grid.snap(2.2) == 2.0 && grid.snap(2.3) == 2.5)
        #expect(grid.nudge(2.0, beats: 2) == 3.0 && grid.nudge(2.0, beats: -10) == 1.0 && grid.nudge(2.0, beats: 100) == 8.5)
    }

    @Test func 변속은_8박_넘게_이어진_템포만() {
        func beats(_ bpm: Double, _ count: Int, from: Double) -> [BeatGrid.Beat] {
            (0..<count).map { BeatGrid.Beat(number: $0 % 4 + 1, bpm: bpm, time: from + Double($0) * 60 / bpm) }
        }
        #expect(grid.tempoChanges.isEmpty)
        let changing = BeatGrid(beats: beats(128, 32, from: 0) + beats(130, 4, from: 15) + beats(150, 32, from: 17))
        #expect(changing.tempoChanges == [128, 150], "4박짜리 130은 흔들림으로 본다")
        let wobble = BeatGrid(beats: beats(128, 32, from: 0) + beats(129, 32, from: 15))
        #expect(wobble.tempoChanges.isEmpty, "2 BPM 안의 흔들림은 같은 템포")
    }
}

@Suite("가져오기 검증·태그 초안")
struct ImportAndTagTests {
    let sent = [GridSegment(start: 0.25, bpm: 150, firstBeatNumber: 1)]

    func rekordboxGrid(start: Double, bpm: Double) -> BeatGrid {
        BeatGrid(beats: (0..<500).map { BeatGrid.Beat(number: $0 % 4 + 1, bpm: bpm, time: start + Double($0) * 60 / bpm) })
    }

    @Test func 보낸_그리드와_비교() {
        typealias Check = StagedTrack.ImportCheck
        #expect(Check.compare(sent: sent, imported: rekordboxGrid(start: 0.25, bpm: 150), duration: 180, checkedOn: "d").result == .matched)
        #expect(Check.compare(sent: sent, imported: rekordboxGrid(start: 0.26, bpm: 150), duration: 180, checkedOn: "d").result == .shifted)
        #expect(Check.compare(sent: sent, imported: rekordboxGrid(start: 0.25, bpm: 151), duration: 180, checkedOn: "d").result == .reanalyzed)
        #expect(Check.compare(sent: sent, imported: nil, duration: 180, checkedOn: "d").result == .pending)
        #expect(Check.compare(sent: [], imported: nil, duration: 180, checkedOn: "d").result == .noGrid)
    }

    @Test func 태그_초안의_바뀐_칸과_문제() {
        let track = Track(id: "1", uuid: "u", title: "원제", artist: "가수", album: nil, albumArtist: nil, genre: nil, composer: nil,
                          releaseYear: 2024, trackNumber: 3, key: nil, bpm: nil, lengthSeconds: 1, folderPath: "/a.mp3",
                          comment: "", importedOn: nil, analysisDataPath: nil, imagePath: nil, isDeleted: false)
        var draft = TagDraft(track: track)
        #expect(!draft.hasChanges && draft.issues.isEmpty)
        draft.fields.comment = "TVA 작품 OP 1"
        draft.fields.year = "2024년"
        draft.fields.title = " "
        #expect(draft.changedKeys == [.title, .year, .comment])
        #expect(draft.issues == ["연도를 숫자로 고친 뒤 rekordbox에 쓰세요", "제목을 입력한 뒤 rekordbox에 쓰세요"])
    }
}
